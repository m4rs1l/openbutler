import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, utimesSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ModuleKind, ScriptTarget, transpileModule } from 'typescript';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { BUILD_ID } from '../src/build-info.js';
import { hostVintageMismatchWarning } from '../src/daemon.js';

const repository = fileURLToPath(new URL('..', import.meta.url));
const stampScript = join(repository, 'scripts', 'write-build-info.mjs');
const buildSource = join(repository, 'src', 'build-info.ts');
let root: string;

function write(rootPath: string, relative: string, contents: string): void {
  const file = join(rootPath, relative);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, contents);
}

function compile(source: string): string {
  return transpileModule(source, {
    compilerOptions: { target: ScriptTarget.ES2023, module: ModuleKind.ESNext },
  }).outputText;
}

function fixture(directory: string, reverse = false): void {
  const files = [
    ['package.json', JSON.stringify({ name: 'build-fixture', version: '1.0.0', type: 'module' })],
    ['src/build-info.ts', readFileSync(buildSource, 'utf8')],
    ['dist/build-info.js', compile(readFileSync(buildSource, 'utf8'))],
    ['dist/cli.js', compile('export const entry: string = "fixture";')],
    ['dist/backend/runtime.js', compile('export const generation: number = 1;')],
    ['dist/client/assets/index.js', 'browser generation 1'],
    ['dist/client/index.html', '<html>browser generation 1</html>'],
    ['dist/backend/runtime.js.map', '{}'],
    ['dist/build-info.d.ts', 'export declare const BUILD_ID: string | null;\n'],
  ] as const;
  for (const [path, contents] of reverse ? [...files].reverse() : files) write(directory, path, contents);
}

function stamp(directory = root): string {
  execFileSync(process.execPath, [stampScript, directory], { encoding: 'utf8', windowsHide: true });
  const literal = readFileSync(join(directory, 'dist', 'build-info.js'), 'utf8');
  expect(literal).toMatch(/^\/\/ Generated by scripts\/write-build-info\.mjs\.\nexport const BUILD_ID = "[a-f0-9]{64}";\n$/);
  return JSON.parse(/export const BUILD_ID = ("[a-f0-9]{64}");/.exec(literal)![1]!);
}

function filesUnder(directory: string, prefix = ''): Record<string, string> {
  const files: Record<string, string> = {};
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) Object.assign(files, filesUnder(join(directory, entry.name), relative));
    else files[relative] = readFileSync(join(directory, entry.name), 'utf8');
  }
  return files;
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'openbutler-build-info-'));
  fixture(root);
});

afterEach(() => {
  if (resolve(dirname(root)) !== resolve(tmpdir()) || !basename(root).startsWith('openbutler-build-info-'))
    throw new Error('Unsafe fixture cleanup.');
  rmSync(root, { recursive: true, force: true });
});

describe('immutable backend build identity', () => {
  it('exports null in source and replaces only the emitted build-info.js', () => {
    expect(BUILD_ID).toBeNull();
    const before = filesUnder(root);
    expect(before['dist/build-info.js']).toContain('export const BUILD_ID = null;');
    stamp();
    const after = filesUnder(root);
    expect(after['dist/build-info.js']).not.toBe(before['dist/build-info.js']);
    delete before['dist/build-info.js'];
    delete after['dist/build-info.js'];
    expect(after).toEqual(before);
  });

  it('defaults to the script project rather than the invoking working directory', () => {
    const fixtureScript = join(root, 'scripts', 'write-build-info.mjs');
    write(root, 'scripts/write-build-info.mjs', readFileSync(stampScript, 'utf8'));
    execFileSync(process.execPath, [fixtureScript], { cwd: tmpdir(), encoding: 'utf8', windowsHide: true });
    const generated = readFileSync(join(root, 'dist', 'build-info.js'), 'utf8');
    expect(generated).toContain('export const BUILD_ID = "');
    stamp();
    expect(readFileSync(join(root, 'dist', 'build-info.js'), 'utf8')).toBe(generated);
  });

  it('is deterministic across creation order, absolute location and repeat stamping', () => {
    const other = join(root, 'other-location');
    fixture(other, true);
    const id = stamp();
    expect(stamp(other)).toBe(id);
    write(root, 'dist/build-info.js', 'export const BUILD_ID = "previous-stamp";\n');
    utimesSync(join(root, 'dist', 'backend', 'runtime.js'), new Date(0), new Date(0));
    expect(stamp()).toBe(id);
    expect(stamp()).toBe(id);
  });

  it('ignores browser assets, declarations and source maps', () => {
    const id = stamp();
    write(root, 'dist/client/assets/index.js', 'browser generation 2');
    write(root, 'dist/client/added.js', 'new browser chunk');
    write(root, 'dist/client/index.html', '<html>browser generation 2</html>');
    write(root, 'dist/backend/runtime.js.map', '{"different":true}');
    write(root, 'dist/build-info.d.ts', 'changed declaration');
    expect(stamp()).toBe(id);
  });

  it('fingerprints nested compiled bytes, filenames and manifest changes', () => {
    const original = stamp();
    write(root, 'dist/backend/runtime.js', compile('export const generation: number = 2;'));
    const changedCode = stamp();
    expect(changedCode).not.toBe(original);
    renameSync(join(root, 'dist', 'backend', 'runtime.js'), join(root, 'dist', 'backend', 'renamed.js'));
    const renamed = stamp();
    expect(renamed).not.toBe(changedCode);
    write(root, 'package.json', JSON.stringify({ name: 'build-fixture', version: '1.0.1', type: 'module' }));
    const changedManifest = stamp();
    expect(changedManifest).not.toBe(renamed);
    write(root, 'dist/backend/added.js', 'export const additional = true;');
    expect(stamp()).not.toBe(changedManifest);
    rmSync(join(root, 'dist', 'backend', 'added.js'));
    expect(stamp()).toBe(changedManifest);
  });

  it('fingerprints dependency resolution and copied terminal modules', () => {
    const original = stamp();
    write(root, 'package-lock.json', JSON.stringify({ lockfileVersion: 3, packages: { fixture: { version: '1.0.0' } } }));
    const withLock = stamp();
    expect(withLock).not.toBe(original);
    write(root, 'package-lock.json', JSON.stringify({ lockfileVersion: 3, packages: { fixture: { version: '1.0.1' } } }));
    const changedLock = stamp();
    expect(changedLock).not.toBe(withLock);
    write(root, 'dist/terminal-host.mjs', 'export const terminalGeneration = 1;');
    const withTerminal = stamp();
    expect(withTerminal).not.toBe(changedLock);
    write(root, 'dist/terminal-host.mjs', 'export const terminalGeneration = 2;');
    expect(stamp()).not.toBe(withTerminal);
  });

  it('keeps already-imported code and ID old while a fresh process imports the second compiled generation', () => {
    const oldId = stamp();
    const infoUrl = pathToFileURL(join(root, 'dist', 'build-info.js')).href;
    const runtimeUrl = pathToFileURL(join(root, 'dist', 'backend', 'runtime.js')).href;
    const nextCode = compile('export const generation: number = 2;');
    const freshProcess = `import { BUILD_ID } from ${JSON.stringify(infoUrl)}; import { generation } from ${JSON.stringify(runtimeUrl)}; process.stdout.write(JSON.stringify({ id: BUILD_ID, generation }));`;
    const result = JSON.parse(
      execFileSync(
        process.execPath,
        [
          '--input-type=module',
          '--eval',
          `import { BUILD_ID } from ${JSON.stringify(infoUrl)};
           import { generation } from ${JSON.stringify(runtimeUrl)};
           import { writeFileSync } from 'node:fs';
           import { execFileSync } from 'node:child_process';
           const before = BUILD_ID;
           writeFileSync(${JSON.stringify(join(root, 'dist', 'backend', 'runtime.js'))}, ${JSON.stringify(nextCode)});
           execFileSync(process.execPath, ${JSON.stringify([stampScript, root])});
           const fresh = JSON.parse(execFileSync(process.execPath, ['--input-type=module', '--eval', ${JSON.stringify(freshProcess)}], { encoding: 'utf8' }));
           const cached = await import(${JSON.stringify(infoUrl)});
           process.stdout.write(JSON.stringify({ before, after: BUILD_ID, cached: cached.BUILD_ID, generation, fresh }));`,
        ],
        { encoding: 'utf8', windowsHide: true },
      ),
    ) as { before: string; after: string; cached: string; generation: number; fresh: { id: string; generation: number } };
    expect(result).toMatchObject({ before: oldId, after: oldId, cached: oldId, generation: 1, fresh: { generation: 2 } });
    expect(result.fresh.id).not.toBe(oldId);
    expect(stamp()).toBe(result.fresh.id);
    const entry = join(root, 'dist', 'cli.js');
    expect(hostVintageMismatchWarning(entry, entry, result.fresh.id, result.after)).toContain('Backend build mismatch');
  });

  it('does not fabricate a stamp when only browser JavaScript exists', () => {
    rmSync(join(root, 'dist', 'cli.js'));
    rmSync(join(root, 'dist', 'backend'), { recursive: true });
    rmSync(join(root, 'dist', 'build-info.js'));
    const result = spawnSync(process.execPath, [stampScript, root], { encoding: 'utf8', windowsHide: true });
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain('No compiled backend JavaScript');
    expect(existsSync(join(root, 'dist', 'build-info.js'))).toBe(false);
  });

  it('stamps at the end of the existing build route used by release packaging', () => {
    const manifest = JSON.parse(readFileSync(join(repository, 'package.json'), 'utf8')) as { scripts: { build: string } };
    expect(manifest.scripts.build).toBe(
      'tsc && node scripts/copy-brand-assets.mjs && node scripts/copy-builtin-skills.mjs && node scripts/copy-terminal-host.mjs && node scripts/write-build-info.mjs',
    );
  });
});
