import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { cliRuntimeArgs } from './cli-entry.js';
import { getDataPath } from './paths.js';
import { loadSettings } from './settings.js';
import { removeTelegramEnvFile, telegramEnvFilePath, writeTelegramEnvFile } from './telegram-setup.js';

const MANAGED_MARKER = 'Managed by OpenButler. Do not edit this file.';
const WINDOWS_RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run';
const WINDOWS_HOST_VALUE = 'OpenButler';
const WINDOWS_WEB_VALUE = 'OpenButlerWeb';
const MACOS_HOST_LABEL = 'ai.openbutler.agent';
const MACOS_WEB_LABEL = 'ai.openbutler.web';
const LINUX_HOST_UNIT = 'openbutler.service';
const LINUX_WEB_UNIT = 'openbutler-web.service';
const AUTOSTART_CONFIG_FILE = 'autostart.json';

/** The binding and workspace a login-started web client should reproduce. */
export type AutostartWeb = { host: string; port: number; dir: string };

/**
 * `web` omitted keeps whatever an existing managed install already had, so a
 * token refresh or a repair never silently turns web startup off. `null`
 * explicitly removes the web client from login startup.
 */
export type AutostartOptions = { web?: AutostartWeb | null | undefined };

type CliCommand = { executable: string; args: string[] };

export function autostartDescription(): string {
  if (process.platform === 'win32') return 'Current Windows user logon';
  if (process.platform === 'darwin') return 'Current macOS user login';
  if (process.platform === 'linux') return 'Current Linux user session (systemd)';
  return `Unsupported platform: ${process.platform}`;
}

export function isAutostartInstalled(): boolean {
  if (process.platform === 'win32') {
    const value = readWindowsRunValue(WINDOWS_HOST_VALUE);
    return value !== null && value.includes(getWindowsHostLauncherPath());
  }
  return isManagedFile(getAutostartFilePath());
}

/**
 * The browser client is installed as its own login entry. It is never a child
 * of the host: starting the host alone must leave web off, and starting web
 * requires the host to already be running.
 */
export function isWebAutostartInstalled(): boolean {
  if (process.platform === 'win32') {
    const value = readWindowsRunValue(WINDOWS_WEB_VALUE);
    return value !== null && value.includes(getWindowsWebLauncherPath());
  }
  return isManagedFile(getWebAutostartFilePath());
}

export function installAutostart(options: AutostartOptions = {}): string {
  const web = options.web === undefined ? readAutostartWeb() : options.web === null ? null : requireAutostartWeb(options.web);
  const host = getCliCommand(['daemon', 'run']);
  const webCommand =
    web === null ? null : getCliCommand(['web', '--serve', '--port', String(web.port), '--hostname', web.host, '--dir', web.dir]);
  // The host never inherits whatever directory happened to be current at logon.
  mkdirSync(getAutostartWorkingDirectory(), { recursive: true });
  let detail: string;
  if (process.platform === 'win32') detail = installWindows(host, webCommand);
  else if (process.platform === 'darwin') detail = installMacos(host, webCommand);
  else if (process.platform === 'linux') detail = installLinux(host, webCommand);
  else throw new Error(`OpenButler automatic startup is not supported on ${process.platform}.`);
  if (web === null) removeAutostartConfig();
  else writeAutostartConfig(web);
  return detail;
}

export function uninstallAutostart(): string {
  let detail: string;
  if (process.platform === 'win32') detail = uninstallWindows();
  else if (process.platform === 'darwin') detail = uninstallMacos();
  else if (process.platform === 'linux') detail = uninstallLinux();
  else throw new Error(`OpenButler automatic startup is not supported on ${process.platform}.`);
  removeAutostartConfig();
  return detail;
}

/** The web binding saved by the last managed install, or null for host-only startup. */
export function readAutostartWeb(): AutostartWeb | null {
  try {
    const parsed: unknown = JSON.parse(readFileSync(getAutostartConfigPath(), 'utf8'));
    if (!isRecord(parsed)) return null;
    return parseAutostartWeb(parsed.web);
  } catch {
    return null;
  }
}

function installWindows(host: CliCommand, web: CliCommand | null): string {
  const hostLauncher = getWindowsHostLauncherPath();
  const webLauncher = getWindowsWebLauncherPath();
  const hostExisting = readWindowsRunValue(WINDOWS_HOST_VALUE);
  if (hostExisting !== null && !hostExisting.includes(hostLauncher)) {
    throw new Error(`The Windows Run value "${WINDOWS_HOST_VALUE}" already belongs to another command; OpenButler left it unchanged.`);
  }
  const webExisting = readWindowsRunValue(WINDOWS_WEB_VALUE);
  if (web !== null && webExisting !== null && !webExisting.includes(webLauncher)) {
    throw new Error(`The Windows Run value "${WINDOWS_WEB_VALUE}" already belongs to another command; OpenButler left it unchanged.`);
  }
  const hostWasManaged = hostExisting !== null;
  const webWasManaged = webExisting !== null && webExisting.includes(webLauncher);
  mkdirSync(dirname(hostLauncher), { recursive: true });
  writeWindowsLauncher(hostLauncher, host);
  if (web !== null) writeWindowsLauncher(webLauncher, web);
  try {
    runCommand('reg.exe', ['add', WINDOWS_RUN_KEY, '/v', WINDOWS_HOST_VALUE, '/t', 'REG_SZ', '/d', `wscript.exe "${hostLauncher}"`, '/f']);
    if (web !== null) {
      runCommand('reg.exe', ['add', WINDOWS_RUN_KEY, '/v', WINDOWS_WEB_VALUE, '/t', 'REG_SZ', '/d', `wscript.exe "${webLauncher}"`, '/f']);
    }
  } catch (error) {
    if (!hostWasManaged) {
      try {
        runCommand('reg.exe', ['delete', WINDOWS_RUN_KEY, '/v', WINDOWS_HOST_VALUE, '/f']);
      } catch {
        /* registration never succeeded */
      }
      unlinkIfExists(hostLauncher);
    }
    if (web !== null && !webWasManaged) {
      try {
        runCommand('reg.exe', ['delete', WINDOWS_RUN_KEY, '/v', WINDOWS_WEB_VALUE, '/f']);
      } catch {
        /* registration never succeeded */
      }
      unlinkIfExists(webLauncher);
    }
    throw error;
  }
  if (web === null) removeWindowsWebEntry();
  return `${autostartDescription()} configured.`;
}

function uninstallWindows(): string {
  const hostLauncher = getWindowsHostLauncherPath();
  const webLauncher = getWindowsWebLauncherPath();
  let removed = false;
  const hostValue = readWindowsRunValue(WINDOWS_HOST_VALUE);
  if (hostValue !== null && hostValue.includes(hostLauncher)) {
    runCommand('reg.exe', ['delete', WINDOWS_RUN_KEY, '/v', WINDOWS_HOST_VALUE, '/f']);
    removed = true;
  }
  const webValue = readWindowsRunValue(WINDOWS_WEB_VALUE);
  if (webValue !== null && webValue.includes(webLauncher)) {
    runCommand('reg.exe', ['delete', WINDOWS_RUN_KEY, '/v', WINDOWS_WEB_VALUE, '/f']);
    removed = true;
  }
  unlinkIfExists(hostLauncher);
  unlinkIfExists(webLauncher);
  return removed ? 'OpenButler automatic startup removed.' : 'OpenButler automatic startup was not installed.';
}

function writeWindowsLauncher(path: string, command: CliCommand): void {
  const commandLine = [command.executable, ...command.args].map(quoteWindowsArgument).join(' ');
  const script = [
    `' ${MANAGED_MARKER}`,
    'Set openbutlerShell = CreateObject("WScript.Shell")',
    `openbutlerShell.Environment("PROCESS")("OPENBUTLER_DATA_DIR") = "${resolve(getDataPath()).replace(/"/g, '""')}"`,
    `openbutlerShell.CurrentDirectory = "${getAutostartWorkingDirectory().replace(/"/g, '""')}"`,
    `openbutlerShell.Run "${commandLine.replace(/"/g, '""')}", 0, False`,
    '',
  ].join('\r\n');
  writeAtomically(path, script);
}

function removeWindowsWebEntry(): void {
  const launcher = getWindowsWebLauncherPath();
  const value = readWindowsRunValue(WINDOWS_WEB_VALUE);
  if (value !== null && value.includes(launcher)) {
    runCommand('reg.exe', ['delete', WINDOWS_RUN_KEY, '/v', WINDOWS_WEB_VALUE, '/f']);
  }
  unlinkIfExists(launcher);
}

function installMacos(host: CliCommand, web: CliCommand | null): string {
  const hostPath = getAutostartFilePath();
  const webPath = getWebAutostartFilePath();
  assertManagedFileCanBeReplaced(hostPath);
  if (web !== null) assertManagedFileCanBeReplaced(webPath);
  writeHostAutostartUnit(hostPath, host);
  if (web !== null) writeWebAutostartUnit(webPath, web);
  else removeMacosWebEntry();
  return `${autostartDescription()} configured.`;
}

function uninstallMacos(): string {
  const hostPath = getAutostartFilePath();
  const webPath = getWebAutostartFilePath();
  const hostInstalled = isManagedFile(hostPath);
  const webInstalled = isManagedFile(webPath);
  if (!hostInstalled && !webInstalled) return 'OpenButler automatic startup was not installed.';
  if (hostInstalled) {
    bootoutMacos(MACOS_HOST_LABEL, hostPath);
    unlinkIfExists(hostPath);
  }
  if (webInstalled) {
    bootoutMacos(MACOS_WEB_LABEL, webPath);
    unlinkIfExists(webPath);
  }
  return 'OpenButler automatic startup removed.';
}

function bootoutMacos(label: string, path: string): void {
  const domain = `gui/${requireUid()}`;
  const loaded = spawnSync('launchctl', ['print', `${domain}/${label}`], { encoding: 'utf8' });
  if (loaded.error) throw loaded.error;
  if (loaded.status === 0) runCommand('launchctl', ['bootout', domain, path]);
}

function removeMacosWebEntry(): void {
  const path = getWebAutostartFilePath();
  if (!isManagedFile(path)) return;
  bootoutMacos(MACOS_WEB_LABEL, path);
  unlinkIfExists(path);
}

function installLinux(host: CliCommand, web: CliCommand | null): string {
  const hostPath = getAutostartFilePath();
  const webPath = getWebAutostartFilePath();
  assertManagedFileCanBeReplaced(hostPath);
  if (web !== null) assertManagedFileCanBeReplaced(webPath);
  writeHostAutostartUnit(hostPath, host);
  if (web !== null) writeWebAutostartUnit(webPath, web);
  try {
    runCommand('systemctl', ['--user', 'daemon-reload']);
    runCommand('systemctl', ['--user', 'enable', LINUX_HOST_UNIT]);
    if (web !== null) runCommand('systemctl', ['--user', 'enable', LINUX_WEB_UNIT]);
  } catch (error) {
    for (const unit of web === null ? [LINUX_HOST_UNIT] : [LINUX_HOST_UNIT, LINUX_WEB_UNIT]) {
      try {
        runCommand('systemctl', ['--user', 'disable', '--now', unit]);
      } catch {
        /* retain original error */
      }
    }
    unlinkIfExists(hostPath);
    if (web !== null) unlinkIfExists(webPath);
    try {
      runCommand('systemctl', ['--user', 'daemon-reload']);
    } catch {
      /* retain original error */
    }
    throw error;
  }
  if (web === null) removeLinuxWebEntry();
  return `${autostartDescription()} configured.`;
}

function uninstallLinux(): string {
  const hostPath = getAutostartFilePath();
  const webPath = getWebAutostartFilePath();
  const hostInstalled = isManagedFile(hostPath);
  const webInstalled = isManagedFile(webPath);
  if (!hostInstalled && !webInstalled) return 'OpenButler automatic startup was not installed.';
  for (const [installed, unit, path] of [
    [hostInstalled, LINUX_HOST_UNIT, hostPath],
    [webInstalled, LINUX_WEB_UNIT, webPath],
  ] as const) {
    if (!installed) continue;
    try {
      runCommand('systemctl', ['--user', 'disable', '--now', unit]);
    } catch {
      /* removing the unit still releases the login entry */
    }
    unlinkIfExists(path);
  }
  removeTelegramEnvFile(telegramEnvFilePath(resolve(getDataPath())));
  runCommand('systemctl', ['--user', 'daemon-reload']);
  return 'OpenButler automatic startup removed.';
}

function removeLinuxWebEntry(): void {
  const path = getWebAutostartFilePath();
  if (!isManagedFile(path)) return;
  try {
    runCommand('systemctl', ['--user', 'disable', '--now', LINUX_WEB_UNIT]);
  } catch {
    /* removing the unit still releases the login entry */
  }
  unlinkIfExists(path);
  try {
    runCommand('systemctl', ['--user', 'daemon-reload']);
  } catch {
    /* the next login still sees the removed file */
  }
}

/**
 * Pure LaunchAgent document builder. `extraEnv` carries secret-class values
 * (today: the Telegram bot token) inline; the file is always written 0600.
 * The label distinguishes the host agent from the independent web agent.
 */
export function buildMacosDocument(
  executable: string,
  args: readonly string[],
  dataDir: string,
  logPath: string,
  extraEnv: Record<string, string>,
  workingDirectory?: string,
  label = MACOS_HOST_LABEL,
): string {
  for (const name of Object.keys(extraEnv)) assertEnvName(name);
  const variables = [`<key>OPENBUTLER_DATA_DIR</key><string>${xmlEscape(dataDir)}</string>`];
  for (const [name, value] of Object.entries(extraEnv)) variables.push(`<key>${name}</key><string>${xmlEscape(value)}</string>`);
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
    `  <key>Label</key><string>${xmlEscape(label)}</string>`,
    `  <key>Comment</key><string>${xmlEscape(MANAGED_MARKER)}</string>`,
    '  <key>ProgramArguments</key>',
    '  <array>',
    `    <string>${xmlEscape(executable)}</string>`,
    ...args.map((argument) => `    <string>${xmlEscape(argument)}</string>`),
    '  </array>',
    `  <key>EnvironmentVariables</key><dict>${variables.join('')}</dict>`,
    ...(workingDirectory === undefined ? [] : [`  <key>WorkingDirectory</key><string>${xmlEscape(workingDirectory)}</string>`]),
    '  <key>RunAtLoad</key><true/>',
    '  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>',
    `  <key>StandardOutPath</key><string>${xmlEscape(logPath)}</string>`,
    `  <key>StandardErrorPath</key><string>${xmlEscape(logPath)}</string>`,
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

/**
 * Pure systemd unit builder. Secrets never go inline: when `envFile` is set
 * the unit reads an optional (`-` prefix) 0600 env file instead, so deleting
 * the file cleanly unwires the secret without touching the unit.
 */
export function buildLinuxUnit(
  executable: string,
  args: readonly string[],
  dataDir: string,
  envFile: string | null,
  workingDirectory?: string,
): string {
  return [
    '[Unit]',
    'Description=OpenButler personal agent host',
    '',
    '[Service]',
    'Type=simple',
    `# ${MANAGED_MARKER}`,
    `ExecStart=${[executable, ...args].map((argument) => systemdQuote(argument)).join(' ')}`,
    ...(workingDirectory === undefined ? [] : [`WorkingDirectory=${systemdQuote(workingDirectory, false)}`]),
    `Environment=${systemdQuote(`OPENBUTLER_DATA_DIR=${dataDir}`, false)}`,
    ...(envFile === null ? [] : [`EnvironmentFile=-${systemdQuote(envFile, false)}`]),
    'Restart=on-failure',
    'RestartSec=3',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ].join('\n');
}

/**
 * The web unit is a client service, not part of the host unit. `Wants` and
 * `After` order it behind the host without making the host start it: starting
 * `openbutler.service` alone still leaves the browser server off.
 */
export function buildLinuxWebUnit(executable: string, args: readonly string[], dataDir: string, workingDirectory?: string): string {
  return [
    '[Unit]',
    'Description=OpenButler browser client',
    `After=${LINUX_HOST_UNIT}`,
    `Wants=${LINUX_HOST_UNIT}`,
    '',
    '[Service]',
    'Type=simple',
    `# ${MANAGED_MARKER}`,
    `ExecStart=${[executable, ...args].map((argument) => systemdQuote(argument)).join(' ')}`,
    ...(workingDirectory === undefined ? [] : [`WorkingDirectory=${systemdQuote(workingDirectory, false)}`]),
    `Environment=${systemdQuote(`OPENBUTLER_DATA_DIR=${dataDir}`, false)}`,
    'Restart=on-failure',
    'RestartSec=3',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ].join('\n');
}

/** Telegram token currently available to this process, if Telegram is configured. */
export function currentTelegramEnv(): { name: string; value: string } | null {
  const telegram = loadSettings().telegram;
  if (!telegram?.enabled) return null;
  const value = process.env[telegram.tokenEnv]?.trim();
  if (!value) return null;
  return { name: telegram.tokenEnv, value };
}

/** Telegram token as plist `EnvironmentVariables` entries (macOS only). */
function telegramExtraEnv(): Record<string, string> {
  const telegram = currentTelegramEnv();
  return telegram === null ? {} : { [telegram.name]: telegram.value };
}

function writeHostAutostartUnit(path: string, command: CliCommand): void {
  const dataDir = resolve(getDataPath());
  const workingDirectory = getAutostartWorkingDirectory();
  if (process.platform === 'darwin') {
    writeAtomically(
      path,
      buildMacosDocument(
        command.executable,
        command.args,
        dataDir,
        getDataPath('daemon.log'),
        telegramExtraEnv(),
        workingDirectory,
        MACOS_HOST_LABEL,
      ),
    );
    return;
  }
  const telegram = currentTelegramEnv();
  let envFile: string | null = null;
  if (telegram !== null) {
    envFile = telegramEnvFilePath(dataDir);
    writeTelegramEnvFile(envFile, telegram.name, telegram.value);
  }
  writeAtomically(path, buildLinuxUnit(command.executable, command.args, dataDir, envFile, workingDirectory));
}

function writeWebAutostartUnit(path: string, command: CliCommand): void {
  const dataDir = resolve(getDataPath());
  const workingDirectory = getAutostartWorkingDirectory();
  if (process.platform === 'darwin') {
    writeAtomically(
      path,
      buildMacosDocument(command.executable, command.args, dataDir, getDataPath('daemon.log'), {}, workingDirectory, MACOS_WEB_LABEL),
    );
    return;
  }
  writeAtomically(path, buildLinuxWebUnit(command.executable, command.args, dataDir, workingDirectory));
}

/**
 * Rewires the already-installed host login entry for the current Telegram token
 * state. The independent web entry is left untouched: it carries no provider or
 * Telegram secrets and must not be rewritten as a side effect.
 */
export function refreshAutostartEnv(): { updated: boolean; detail: string } {
  if (currentTelegramEnv() === null) removeTelegramEnvFileIfUnused();
  if (process.platform === 'win32')
    return { updated: false, detail: 'Windows login startup inherits the user environment; nothing to update.' };
  if (process.platform !== 'darwin' && process.platform !== 'linux')
    return { updated: false, detail: 'Login startup is not supported on this platform.' };
  if (!isAutostartInstalled())
    return {
      updated: false,
      detail:
        'Automatic startup is not installed; the token applies to the current host. Run `openbutler daemon install` to also cover user login.',
    };
  const path = getAutostartFilePath();
  try {
    assertManagedFileCanBeReplaced(path);
  } catch {
    return {
      updated: false,
      detail: `Login startup file is user-modified, left unchanged: ${path}. Wire the token variable there manually.`,
    };
  }
  writeHostAutostartUnit(path, getCliCommand(['daemon', 'run']));
  if (process.platform === 'linux') {
    try {
      runCommand('systemctl', ['--user', 'daemon-reload']);
    } catch (error) {
      return {
        updated: true,
        detail: `Login unit rewritten, but daemon-reload failed: ${error instanceof Error ? error.message : String(error)}`,
      };
    }
    removeTelegramEnvFileIfUnused();
    return { updated: true, detail: 'Login unit rewritten for the current token state; applies at the next user login.' };
  }
  return { updated: true, detail: 'Login agent rewritten for the current token state; applies at the next user login.' };
}

/** Deletes the systemd env file when no Telegram token is configured anymore. */
function removeTelegramEnvFileIfUnused(): void {
  if (currentTelegramEnv() === null) removeTelegramEnvFile(telegramEnvFilePath(resolve(getDataPath())));
}

function assertEnvName(name: string): void {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`Refusing to write an invalid environment variable name: ${name}`);
}

function getAutostartFilePath(): string {
  if (process.platform === 'darwin') return join(homedir(), 'Library', 'LaunchAgents', `${MACOS_HOST_LABEL}.plist`);
  if (process.platform === 'linux')
    return join(process.env.XDG_CONFIG_HOME ?? join(homedir(), '.config'), 'systemd', 'user', LINUX_HOST_UNIT);
  if (process.platform === 'win32') return getWindowsHostLauncherPath();
  throw new Error(`OpenButler automatic startup is not supported on ${process.platform}.`);
}

function getWebAutostartFilePath(): string {
  if (process.platform === 'darwin') return join(homedir(), 'Library', 'LaunchAgents', `${MACOS_WEB_LABEL}.plist`);
  if (process.platform === 'linux')
    return join(process.env.XDG_CONFIG_HOME ?? join(homedir(), '.config'), 'systemd', 'user', LINUX_WEB_UNIT);
  if (process.platform === 'win32') return getWindowsWebLauncherPath();
  throw new Error(`OpenButler automatic startup is not supported on ${process.platform}.`);
}

function getWindowsHostLauncherPath(): string {
  return resolve(getDataPath(join('autostart', 'openbutler-logon.vbs')));
}

function getWindowsWebLauncherPath(): string {
  return resolve(getDataPath(join('autostart', 'openbutler-web-logon.vbs')));
}

function getAutostartWorkingDirectory(): string {
  return resolve(getDataPath('custodian'));
}

function getAutostartConfigPath(): string {
  return resolve(getDataPath(AUTOSTART_CONFIG_FILE));
}

function getCliCommand(command: string[]): CliCommand {
  const entry = process.argv[1];
  if (!entry) throw new Error('Could not locate the OpenButler CLI entry point.');
  return { executable: resolve(process.execPath), args: [...cliRuntimeArgs(entry), resolve(entry), ...command] };
}

/** Rejects a login entry that would fail on a later boot instead of at install time. */
function requireAutostartWeb(web: AutostartWeb): AutostartWeb {
  const parsed = parseAutostartWeb(web);
  if (!parsed) {
    throw new Error('Automatic web startup needs a host without spaces, a port between 1 and 65535, and an absolute --dir.');
  }
  return parsed;
}

function parseAutostartWeb(raw: unknown): AutostartWeb | null {
  if (!isRecord(raw)) return null;
  const { host, port, dir } = raw;
  if (typeof host !== 'string' || !host || host.length > 255 || /[\s\0]/.test(host)) return null;
  if (typeof port !== 'number' || !Number.isInteger(port) || port < 1 || port > 65535) return null;
  if (typeof dir !== 'string' || !isAbsolute(dir)) return null;
  return { host, port, dir };
}

function writeAutostartConfig(web: AutostartWeb): void {
  writeAtomically(getAutostartConfigPath(), `${JSON.stringify({ web }, null, 2)}\n`);
}

function removeAutostartConfig(): void {
  unlinkIfExists(getAutostartConfigPath());
}

function isManagedFile(path: string): boolean {
  try {
    return readFileSync(path, 'utf8').includes(MANAGED_MARKER);
  } catch {
    return false;
  }
}

function assertManagedFileCanBeReplaced(path: string): void {
  if (!existsSync(path)) return;
  if (!readFileSync(path, 'utf8').includes(MANAGED_MARKER)) {
    throw new Error(`Refusing to overwrite an existing user service file: ${path}`);
  }
}

function writeAtomically(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  const temporaryPath = `${path}.${process.pid}.tmp`;
  writeFileSync(temporaryPath, content, { encoding: 'utf8', mode: 0o600 });
  try {
    unlinkSync(path);
  } catch {
    /* first install */
  }
  renameSync(temporaryPath, path);
}

function unlinkIfExists(path: string): void {
  try {
    unlinkSync(path);
  } catch (error) {
    if (isRecord(error) && error.code !== 'ENOENT') throw error;
  }
}

function readWindowsRunValue(name: string): string | null {
  const result = spawnSync('reg.exe', ['query', WINDOWS_RUN_KEY, '/v', name], { encoding: 'utf8', windowsHide: true });
  if (result.status !== 0) return null;
  return `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
}

function runCommand(command: string, args: string[]): void {
  const result = spawnSync(command, args, { encoding: 'utf8', windowsHide: true, timeout: 30_000 });
  if (result.error) throw new Error(`${command} failed: ${result.error.message}`);
  if (result.status !== 0) {
    const output = `${result.stderr ?? ''}${result.stdout ?? ''}`.trim();
    throw new Error(`${command} exited with code ${String(result.status)}.${output ? ` ${output}` : ''}`);
  }
}

function systemdQuote(value: string, escapeDollar = true): string {
  if (/[\r\n\0]/.test(value)) throw new Error('Service command contains a line break.');
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%');
  return `"${escapeDollar ? escaped.replace(/\$/g, () => '$$') : escaped}"`;
}

function quoteWindowsArgument(value: string): string {
  if (!/[\s"]/.test(value)) return value;
  let result = '"';
  let slashes = 0;
  for (const character of value) {
    if (character === '\\') {
      slashes += 1;
      continue;
    }
    if (character === '"') result += '\\'.repeat(slashes * 2 + 1) + '"';
    else result += '\\'.repeat(slashes) + character;
    slashes = 0;
  }
  return result + '\\'.repeat(slashes * 2) + '"';
}

function xmlEscape(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

function requireUid(): number {
  const uid = process.getuid?.();
  if (!Number.isSafeInteger(uid) || uid === undefined) throw new Error('Could not determine the current macOS user id.');
  return uid;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}
