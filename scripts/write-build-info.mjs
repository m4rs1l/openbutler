import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// An optional project root allows isolated build fixtures; normal builds use this repository.
if (process.argv.length > 3) throw new Error('Usage: node scripts/write-build-info.mjs [project-root]');
const root = resolve(process.argv[2] ?? fileURLToPath(new URL('..', import.meta.url)));
const dist = join(root, 'dist');

function backendFiles(directory, prefix = '') {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (relative === 'client' || relative === 'build-info.js') continue;
    if (entry.isDirectory()) files.push(...backendFiles(join(directory, entry.name), relative));
    else if (entry.isFile() && /\.(?:mjs|js)$/.test(entry.name)) files.push(relative);
  }
  return files;
}

const files = backendFiles(dist).sort();
if (files.length === 0) throw new Error('No compiled backend JavaScript found in dist. Run tsc before stamping the build.');
const hash = createHash('sha256').update('openbutler-backend-build-v1\0');
function fingerprint(path, contents) {
  // Frame both the relative path and byte length so file boundaries cannot alias.
  hash.update(JSON.stringify([path, contents.length]) + '\n').update(contents);
}
fingerprint('package.json', readFileSync(join(root, 'package.json')));
if (existsSync(join(root, 'package-lock.json'))) fingerprint('package-lock.json', readFileSync(join(root, 'package-lock.json')));
for (const file of files) fingerprint(`dist/${file}`, readFileSync(join(dist, file)));

// Never derive this identity at runtime: an already-imported host must retain its old generation after a rebuild.
writeFileSync(
  join(dist, 'build-info.js'),
  `// Generated by scripts/write-build-info.mjs.\nexport const BUILD_ID = ${JSON.stringify(hash.digest('hex'))};\n`,
);
